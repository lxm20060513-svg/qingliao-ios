import SwiftUI

// MARK: - v3.9.26 全站间距令牌（Spacing）
//
// 背景：改造前 `.padding(…)` 的字面值散落 **35 档 / 766 处**，其中 1 / 1.5 / 2.5 / 3 / 7 / 8.5 / 9 /
// 11 / 13 / 15 / 17 这些「单发或与邻近档只差 1pt」的值共 100 处 —— 同屏出现 7/8/9/10 或
// 10/11/12 时肉眼分不出层级，是「不够精致」的机械成因之一，与圆角/字号属同一类问题。
//
// 目标：**元素级间距收敛为 8 档**，每处移动幅度 ≤1pt。
// 与 Typography / Radius 同一条纪律：本机无 Xcode SDK 无法目视验证，不搞大步长重排。
//
// ⚠️ **刻意不纳入本体系的五类间距**（别硬套，套了会误导读者）：
//   1. **页面级外边距**（18 / 20 / 22 / 24 / 26 / 28 / 30 / 32 / 40 / 44）——它们与元素级间距不属同
//      一尺度层，且改档会整体挪版式；是否收敛需真机逐屏确认，属单独一轮。
//      （22 / 24 / 26 / 32 / 40 / 44 是 v3.9.26 复查时补进本名单的：它们既不在 8 档内、也不在原名单，
//      于是「既不计数也不报警」漏过 —— `apply_spacing.py` 已加未知档桶，非空即断言失败，不再空真。）
//   2. **布局避让值**（52 / 60 / 62 / 78 / 90 / 100）——键盘 / dock / 安全区避让，是「必须等于某个
//      具体高度」的数值，不是审美尺度，严禁归位。
//   3. **由调用方传入的参数**（`.padding(inset)` 这类）——参数传递不是魔法数。
//   4. **栈间距**（`VStack/HStack(spacing:)` 的参数，全仓 485 处）——本轮只收 `.padding` 维度；
//      栈间距与内边距混在同一个令牌名下有歧义，属单独一轮。**新写的代码别在这里用令牌**
//      （否则同屏两种写法，下一轮 grep 只会找到一半）。
//   5. **挂件 target**（qingliaoWidget）——它不引用本文件（令牌文件未加进它的 sources），其 padding 另论。
//
// 命名刻意用**尺度梯度名**（xxs→section）而非用途名（如「卡片内边距」）：同一个 12 在不同位置
// 可能是卡片内边距、也可能是卡片间距，用用途名会与调用点语义错位。名字只声明「这是全站口径的哪一档」，
// 用途由调用点决定 —— 与 Tint 保持 4 档、不盲目扩档是同一个原则。
//
// 件数基线（令牌引用总数，用于回归断言）：xxs 43 · xs 93 · sm 53 · md 94 · lg 100 · xl 96 · xxl 87 · section 37
// ⚠️ 调整档位或做新一轮替换后，必须同步更新这组基线（断言脚本属本机运维工具，不随仓库分发）。

enum Spacing {
    /// 2pt — 极小间隙（角标内衬、紧贴元素）
    static let xxs: CGFloat = 2
    /// 4pt — 同组元素（图标与文字、按钮内衬）
    static let xs: CGFloat = 4
    /// 6pt — 紧密堆叠（两行文字、列表行内）
    static let sm: CGFloat = 6
    /// 8pt — 卡内元素间距
    static let md: CGFloat = 8
    /// 10pt — 常规间距
    static let lg: CGFloat = 10
    /// 12pt — 卡片内边距 / 卡片间距
    static let xl: CGFloat = 12
    /// 14pt — 卡片内边距（主力档）
    static let xxl: CGFloat = 14
    /// 16pt — 分区之间
    static let section: CGFloat = 16

    // MARK: - v3.9.80 语义常量（跨文件同一概念的单一真源）
    //
    // 为什么加在 Spacing 里：这些值本来散在各处当字面量写（52 出现 46 次、水平留白写过 18/20 两种），
    // 改一处要翻五个文件；抽成命名常量后「改口径只改这里」，真值表 ql_theme 会盯着它们。

    /// 18pt — **弹窗/设置页「非卡片内容」左右留白**（分组标题、说明文字、错误提示、按钮行同口径）。
    /// 与 `SectionHeader` 的行内边距一致（真源 SettingsSheets.swift 的 SectionHeader）；
    /// 收敛前同一概念写过 18（12 处）与 20（9 处）两种 → 统一到 18（多数 + 与分组标题对齐）。
    static let sheetInset: CGFloat = 18
    /// 54pt — **设置页行内分隔线左缩进**（让分隔线正好从行文字左边缘起画）。
    /// 算式（见 SettingRow）：行内留白 14 + 图标 28 + 图标与文字间距 12 = **54**。
    /// v3.9.80：收敛前 46 处写 52（比算式少 2pt，分隔线压进图标列 2pt）→ 用户拍板「严格按算式对齐」，
    /// 本版全量改成 54（46 处分隔线各右移 2pt，肉眼不可辨，但从此算式与取值一致、改图标尺寸时真值表会红）。
    static let rowDividerInset: CGFloat = 54
    /// 62pt — **36pt 图标行**的分隔线缩进（cron 任务列表那种「图标 36 + 两行文字」的行）：
    /// 与算式 14 + 36 + 12 = 62 逐字一致（收敛前是 SettingsPages.swift 里唯一一处写 62 的字面量）。
    static let rowDividerInsetWide: CGFloat = 62
}
